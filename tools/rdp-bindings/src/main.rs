//! Regenerates `src/rdp/windows/bindings.rs` from Windows metadata.
//!
//! Usage: `alighieri-rdp-bindings <Windows.Win32.winmd> <output.rs> <metadata-version>`.
//! Run it through `scripts/generate-rdp-bindings.sh`, which downloads the
//! pinned metadata and verifies its checksum first.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::{env, fs};

const FILTER: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/filter.txt");

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let [winmd, output, version] = args.as_slice() else {
        eprintln!("usage: alighieri-rdp-bindings <Windows.Win32.winmd> <output.rs> <metadata-version>");
        std::process::exit(2);
    };
    let output = PathBuf::from(output);

    windows_bindgen::bindgen([
        "--in",
        winmd,
        "--out",
        path_str(&output),
        "--filter-file",
        FILTER,
        "--flat",
    ]);

    let generated = fs::read_to_string(&output).expect("read generated bindings");
    let header = format!(
        "// Generated by tools/rdp-bindings from Microsoft.Windows.SDK.Win32Metadata\n\
         // {version}. Do not edit: run scripts/generate-rdp-bindings.sh instead.\n\
         \n\
         #![allow(\n\
         \x20   non_camel_case_types,\n\
         \x20   non_snake_case,\n\
         \x20   non_upper_case_globals,\n\
         \x20   dead_code,\n\
         \x20   clippy::all,\n\
         \x20   clippy::pedantic\n\
         )]\n\n"
    );
    fs::write(&output, header + &generated).expect("write bindings");

    // windows-bindgen formats with the 2024 style edition; reformat with the
    // main crate's edition so `cargo fmt --check` accepts the committed file.
    let status = Command::new("rustfmt")
        .args(["--edition", "2021"])
        .arg(&output)
        .status()
        .expect("run rustfmt");
    assert!(status.success(), "rustfmt failed on {}", output.display());
}

fn path_str(path: &Path) -> &str {
    path.to_str().expect("output path must be UTF-8")
}
